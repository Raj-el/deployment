-- Summary by status
SELECT 
  status,
  COUNT(*) as assignment_count,
  SUM(estimated_hours) as total_estimated_hours,
  SUM(actual_hours) as total_actual_hours,
  ROUND(AVG(client_satisfaction_score), 2) as avg_satisfaction
FROM "ExpertAssignments"
WHERE client_id = (SELECT client_id FROM "Clients" WHERE slug = 'scalepoint')
GROUP BY status
ORDER BY 
  CASE status 
    WHEN 'active' THEN 1 
    WHEN 'pending' THEN 2 
    WHEN 'completed' THEN 3 
    WHEN 'cancelled' THEN 4 
  END;

-- Assignments by expert
SELECT 
  e.expert_id,
  e.name,
  e.department,
  e.expert_level,
  COUNT(ea.assignment_id) as total_assignments,
  COUNT(*) FILTER (WHERE ea.status = 'active') as active_assignments,
  COUNT(*) FILTER (WHERE ea.status = 'completed') as completed_assignments,
  ROUND(AVG(ea.client_satisfaction_score), 2) as avg_satisfaction,
  SUM(ea.actual_hours) as total_hours_delivered
FROM "Experts" e
LEFT JOIN "ExpertAssignments" ea ON e.expert_id = ea.expert_id
WHERE ea.client_id = (SELECT client_id FROM "Clients" WHERE slug = 'scalepoint')
  OR ea.client_id IS NULL
GROUP BY e.expert_id, e.name, e.department, e.expert_level
ORDER BY total_assignments DESC;

-- Assignments by type
SELECT 
  assignment_type,
  COUNT(*) as assignment_count,
  COUNT(*) FILTER (WHERE status = 'completed') as completed_count,
  ROUND(AVG(estimated_hours), 1) as avg_estimated_hours,
  ROUND(AVG(actual_hours), 1) as avg_actual_hours,
  ROUND(AVG(client_satisfaction_score), 2) as avg_satisfaction
FROM "ExpertAssignments"
WHERE client_id = (SELECT client_id FROM "Clients" WHERE slug = 'scalepoint')
GROUP BY assignment_type
ORDER BY assignment_count DESC
LIMIT 15;

-- Active assignments requiring attention
SELECT 
  e.expert_id,
  e.name,
  ea.assignment_type,
  ea.priority,
  ea.account_id,
  ccd.account_name,
  ea.estimated_hours,
  ea.actual_hours,
  ea.assigned_at,
  EXTRACT(DAY FROM (NOW() - ea.assigned_at)) as days_open
FROM "ExpertAssignments" ea
JOIN "Experts" e ON ea.expert_id = e.expert_id
LEFT JOIN "ClientCustomerData" ccd ON ea.account_id = ccd.account_id
WHERE ea.client_id = (SELECT client_id FROM "Clients" WHERE slug = 'scalepoint')
  AND ea.status = 'active'
ORDER BY 
  CASE ea.priority 
    WHEN 'urgent' THEN 1 
    WHEN 'high' THEN 2 
    WHEN 'normal' THEN 3 
    WHEN 'low' THEN 4 
  END,
  ea.assigned_at;

-- Completed assignments with high satisfaction
SELECT 
  e.name as expert_name,
  e.department,
  ea.assignment_type,
  ccd.account_name,
  ccd.account_type,
  ea.actual_hours,
  ea.client_satisfaction_score,
  ea.outcome_summary,
  ea.completed_at
FROM "ExpertAssignments" ea
JOIN "Experts" e ON ea.expert_id = e.expert_id
LEFT JOIN "ClientCustomerData" ccd ON ea.account_id = ccd.account_id
WHERE ea.client_id = (SELECT client_id FROM "Clients" WHERE slug = 'scalepoint')
  AND ea.status = 'completed'
  AND ea.client_satisfaction_score >= 4
ORDER BY ea.client_satisfaction_score DESC, ea.completed_at DESC
LIMIT 20;

-- Expert utilization by department
SELECT 
  e.department,
  COUNT(DISTINCT e.expert_id) as expert_count,
  COUNT(ea.assignment_id) as total_assignments,
  ROUND(AVG(ea.actual_hours), 1) as avg_hours_per_assignment,
  SUM(ea.actual_hours) as total_hours_delivered,
  ROUND(AVG(ea.client_satisfaction_score), 2) as avg_satisfaction
FROM "Experts" e
LEFT JOIN "ExpertAssignments" ea ON e.expert_id = ea.expert_id
WHERE ea.client_id = (SELECT client_id FROM "Clients" WHERE slug = 'scalepoint')
  OR ea.client_id IS NULL
GROUP BY e.department
ORDER BY total_assignments DESC;

-- Account-specific vs Client-level assignments
SELECT 
  CASE 
    WHEN account_id IS NOT NULL THEN 'Account-Specific'
    ELSE 'Client-Level'
  END as assignment_scope,
  COUNT(*) as assignment_count,
  ROUND(AVG(estimated_hours), 1) as avg_estimated_hours,
  ROUND(AVG(actual_hours), 1) as avg_actual_hours,
  COUNT(*) FILTER (WHERE status = 'completed') as completed_count,
  ROUND(AVG(client_satisfaction_score), 2) as avg_satisfaction
FROM "ExpertAssignments"
WHERE client_id = (SELECT client_id FROM "Clients" WHERE slug = 'scalepoint')
GROUP BY assignment_scope;

